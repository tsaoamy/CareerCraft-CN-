export type TranslationKeys = (typeof translations)[Locale];

/** 英文模式下将默认中文用户名本地化 */
export function formatDisplayName(name: string, locale: Locale): string {
  if (locale === 'en' && /^用户(\d+)$/.test(name)) {
    return `User${name.slice(2)}`;
  }
  return name;
}

/** 头像默认字符 */
export function getAvatarFallbackChar(
  displayName: string,
  avatarChar: string | undefined,
  locale: Locale
): string {
  const fallback = translations[locale].common.defaultUserChar;
  const source = avatarChar || displayName || fallback;
  const char = source.charAt(0).toUpperCase();
  if (locale === 'en' && /[\u4e00-\u9fff]/.test(char)) {
    return fallback;
  }
  return char;
}
